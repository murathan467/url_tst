-- 1. skins tablosu (UNLOGGED: WAL Disk IO ve RAM baskısını minimuma indirir; id PRIMARY KEY ve skin_id UNIQUE otomatik indekslidir)
CREATE UNLOGGED TABLE IF NOT EXISTS public.skins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skin_id TEXT NOT NULL UNIQUE,
    skin_name TEXT DEFAULT '',
    wear_value TEXT DEFAULT '',
    processed_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. system_state tablosu (Son taranan ID ve sistem durumu — key_name UNIQUE otomatik indekslidir)
CREATE TABLE IF NOT EXISTS public.system_state (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key_name TEXT NOT NULL UNIQUE,
    key_value TEXT DEFAULT '',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. notified_bargains tablosu (Bildirilen fırsatların tekrar bildirilmemesi için)
CREATE TABLE IF NOT EXISTS public.notified_bargains (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skin_name TEXT NOT NULL,
    seller TEXT NOT NULL,
    float_value TEXT DEFAULT '',
    notified_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS notified_bargains_skin_seller_float_key
ON public.notified_bargains (skin_name, seller, float_value);

-- 4. skipped_bargains tablosu (Atlanan fırsatların kayıtları)
CREATE TABLE IF NOT EXISTS public.skipped_bargains (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skin_name TEXT,
    seller TEXT,
    float_value TEXT,
    skipped_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. DEADLOCK & LOCK CONTENTION ÖNLEYİCİ ATOMİK İŞ ÇEKİCİ (FOR UPDATE SKIP LOCKED)
-- Çoklu worker (20 işçi) aynı anda çağırdığında birbirini ASLA bloklamaz ve zaman aşımı yaratmaz.
CREATE OR REPLACE FUNCTION public.get_and_delete_skins(batch_limit INT DEFAULT 10)
RETURNS TABLE (
    skin_id TEXT,
    skin_name TEXT,
    wear_value TEXT
) 
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RETURN QUERY
    WITH selected_rows AS (
        SELECT s.id
        FROM public.skins s
        ORDER BY s.id ASC
        LIMIT batch_limit
        FOR UPDATE SKIP LOCKED
    )
    DELETE FROM public.skins s
    USING selected_rows sr
    WHERE s.id = sr.id
    RETURNING s.skin_id, s.skin_name, s.wear_value;
END;
$$;

-- Fonksiyon izinlerini tanımla
GRANT EXECUTE ON FUNCTION public.get_and_delete_skins(INT) TO anon, authenticated, service_role;
